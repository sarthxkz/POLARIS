// Generates src/components/globe/glyphs.ts: inner SVG markup of the Lucide icons used as globe
// markers, so the globe and the interface share one icon set without a runtime renderer.
// Run: node scripts/gen-marker-glyphs.mjs
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { join } from "node:path";

const icons = {
  wildfires: "flame",
  severeStorms: "tornado",
  volcanoes: "mountain",
  seaLakeIce: "snowflake",
  snow: "snowflake",
  floods: "waves-horizontal",
  landslides: "mountain-snow",
  dustHaze: "haze",
  drought: "sun-dim",
  tempExtremes: "thermometer-sun",
  waterColor: "droplets",
  manmade: "factory",
  plane: "plane",
  satellite: "satellite",
};

const toAttrs = (props) =>
  Object.entries(props)
    .filter(([k]) => k !== "key")
    .map(([k, v]) => `${k.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase())}="${v}"`)
    .join(" ");

const out = {};
for (const [key, name] of Object.entries(icons)) {
  const url = pathToFileURL(join("node_modules", "lucide-react", "dist", "esm", "icons", `${name}.mjs`));
  const mod = await import(url.href);
  const node = mod.__iconData?.node ?? mod.__iconNode;
  if (!node) throw new Error(`No icon data for ${name}`);
  out[key] = node.map(([tag, props]) => `<${tag} ${toAttrs(props)}/>`).join("");
}

const body =
  "// Generated by scripts/gen-marker-glyphs.mjs from lucide-react (ISC licence). Do not edit.\n" +
  "export const GLYPHS = " + JSON.stringify(out, null, 2) + " as const;\n";
writeFileSync("src/components/globe/glyphs.ts", body);
console.log("wrote", Object.keys(out).length, "glyphs");
